export default function Sidebar() {
  const pathname = usePathname();

  const navItems = [
    { href: '/', label: 'Dashboard', icon: icons.dashboard },
    { href: '/students', label: 'Students', icon: icons.students },
    { href: '/teachers', label: 'Teachers', icon: icons.teachers },
    { href: '/courses', label: 'Courses', icon: icons.courses },
  ];

  return (
    <aside className="hidden md:fixed md:top-16 md:left-0 md:bottom-0 md:w-64 md:bg-white md:border-r md:border-[#E8E8E8] md:p-4 md:overflow-y-auto md:z-30">
      <nav className="space-y-1">
        {navItems.map((item) => {
          const isActive = pathname === item.href || (item.href !== '/' && pathname.startsWith(item.href));
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`sidebar-link ${isActive ? 'sidebar-link-active' : 'sidebar-link-inactive'}`}
            >
              <span aria-hidden="true">{item.icon}</span>
              {item.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}